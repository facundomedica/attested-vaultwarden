#!/usr/bin/env bash
# Bring up the LOCAL INSECURE MOCK deployment.
#
#   deploy/local/up.sh
#
# 1. starts a throwaway local registry on 127.0.0.1:5001,
# 2. builds the sidecar image and pushes it there to obtain a digest,
# 3. renders .generated/docker-compose.yml (sidecar pinned by digest),
# 4. wraps it into .generated/app-compose.json (dstack-style wrapper),
# 5. writes .generated/policy-mock.toml (compose hash + image allowlist),
# 6. starts the stack and waits until the attestation endpoint answers,
# 7. exports Caddy's local root CA to .generated/root.crt.
set -euo pipefail

here="$(cd "$(dirname "$0")" && pwd)"
root="$(cd "$here/../.." && pwd)"
gen="$here/.generated"
mkdir -p "$gen"

REGISTRY_IMAGE="docker.io/library/registry@sha256:82f6ff4a7f982960c8aa51617fea3aabc485df6e55cce80d22deb1de36f1bc3c" # registry:3
if ! docker inspect avw-registry >/dev/null 2>&1; then
  docker run -d --name avw-registry -p 127.0.0.1:5001:5000 "$REGISTRY_IMAGE" >/dev/null
fi

echo "==> building sidecar image"
docker build -q -f "$root/attest-sidecar/Dockerfile" -t localhost:5001/attest-sidecar:dev "$root" >/dev/null
docker push -q localhost:5001/attest-sidecar:dev >/dev/null
digest="$(docker buildx imagetools inspect localhost:5001/attest-sidecar:dev --format '{{json .Manifest}}' | jq -r .digest)"
attest_image="localhost:5001/attest-sidecar@${digest}"
echo "    $attest_image"

sed "s|__ATTEST_IMAGE__|${attest_image}|" "$here/docker-compose.template.yml" > "$gen/docker-compose.yml"
jq -n --rawfile c "$gen/docker-compose.yml" \
  '{manifest_version: 2, name: "attested-vaultwarden-local", runner: "docker-compose", docker_compose_file: $c}' \
  > "$gen/app-compose.json"
compose_hash="$(shasum -a 256 "$gen/app-compose.json" | cut -d' ' -f1)"

vw_image="$(grep -E '^\s+image: docker.io/vaultwarden' "$gen/docker-compose.yml" | awk '{print $2}')"
caddy_image="$(grep -E '^\s+image: docker.io/library/caddy' "$gen/docker-compose.yml" | awk '{print $2}')"
cat > "$gen/policy-mock.toml" <<TOML
# GENERATED by deploy/local/up.sh. INSECURE MOCK policy for local development.
schema = 1
release = "local-mock"
date = "$(date -u +%Y-%m-%d)"
platform = "mock"
# The mock sidecar reads the app-compose from a file next to the compose (on
# dstack it comes from the guest agent); the policy must allow that bind.
allowed_bind_mounts = ["attest:./app-compose.json:/etc/attest/app-compose.json:ro"]

[mock]
compose_hash = "${compose_hash}"

[[images]]
service = "attest"
image = "${attest_image}"

[[images]]
service = "proxy"
image = "${caddy_image}"

[[images]]
service = "vaultwarden"
image = "${vw_image}"
TOML

echo "==> starting stack (compose hash ${compose_hash})"
docker compose -f "$gen/docker-compose.yml" up -d --quiet-pull

zero="$(printf '0%.0s' $(seq 1 64))"
for i in $(seq 1 60); do
  if curl -skf "https://localhost:8443/.well-known/tee-attestation?nonce=${zero}" >/dev/null 2>&1; then
    break
  fi
  if [ "$i" = 60 ]; then
    echo "attestation endpoint did not come up" >&2
    docker compose -f "$gen/docker-compose.yml" logs --tail 50 >&2
    exit 1
  fi
  sleep 1
done
docker compose -f "$gen/docker-compose.yml" cp proxy:/data/caddy/pki/authorities/local/root.crt "$gen/root.crt" >/dev/null
echo "==> up: https://localhost:8443 (root CA: $gen/root.crt, policy: $gen/policy-mock.toml)"
